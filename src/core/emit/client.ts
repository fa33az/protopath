import type { FlowAnalysis } from '../pipeline.js';
import { VERSION } from '../pipeline.js';
import type { Field } from '../infer/fields.js';
import type { FramingHypothesis } from '../infer/framing.js';
import { checksumSource } from './checksum-source.js';

export type ClientLanguage = 'ts' | 'python';

interface Layout {
  hypothesis: FramingHypothesis;
  head: Field[];
  payload?: Field;
  tail: Field[];
  checksum?: Field;
}

/**
 * Emits a client that decodes and re-encodes the inferred message shape.
 *
 * The encoder is only emitted when the total message length can be derived from the
 * inferred fields; a variable-length protocol with no length field cannot be encoded from
 * a field model, and the generator says so in a comment instead of guessing.
 */
export function emitClient(analysis: FlowAnalysis, language: ClientLanguage): string {
  const direction = analysis.primary === 'forward' ? analysis.forward : analysis.reverse;
  const hypothesis = direction.best;
  const layout = layoutOf(direction.fields, hypothesis);

  if (!layout) {
    return `# protopath ${VERSION}: no confident message model for ${direction.label}\n# run "protopath analyze" and read the framing hypotheses before generating a client\n`;
  }

  return language === 'ts' ? emitTypeScript(analysis, direction.label, layout) : emitPython(analysis, direction.label, layout);
}

function layoutOf(fields: Field[], hypothesis: FramingHypothesis | undefined): Layout | null {
  if (!hypothesis || fields.length === 0) return null;
  const head = fields.filter((f) => f.anchor === 'head' && f.role !== 'payload').sort((a, b) => a.offset - b.offset);
  const payload = fields.find((f) => f.role === 'payload');
  const tail = fields.filter((f) => f.anchor === 'tail').sort((a, b) => b.offset - a.offset);
  const checksum = tail.find((f) => f.role === 'checksum');
  return { hypothesis, head, ...(payload ? { payload } : {}), tail, ...(checksum ? { checksum } : {}) };
}

function emitTypeScript(analysis: FlowAnalysis, directionLabel: string, layout: Layout): string {
  const { hypothesis } = layout;
  const headerLength = headerBytes(layout);
  const trailerBytes = trailerLength(layout);
  const lengthField = layout.head.find((f) => f.role === 'length');
  const constantLength = hypothesis.kind === 'fixed' ? hypothesis.fixed!.size : null;
  const checksum = layout.checksum;
  const checksumImpl = checksum ? checksumSource(checksum.algorithm ?? '') : null;

  const out: string[] = [];
  out.push(`// Generated by protopath ${VERSION} from ${analysis.capturePath || analysis.forward.label}`);
  out.push(`// Direction: ${directionLabel}`);
  out.push(`// Framing: ${describe(hypothesis)} (confidence ${hypothesis.score.toFixed(2)}, ${hypothesis.messages.length} messages)`);
  out.push(`// Field offsets are inferred. Verify against a known-good implementation before trusting them.`);
  out.push('');
  out.push(`import { Buffer } from 'node:buffer';`);
  out.push('');
  out.push(`export const HEADER_LENGTH = ${headerLength};`);
  out.push(`export const TRAILER_LENGTH = ${trailerBytes};`);
  if (lengthField && hypothesis.lengthPrefix) {
    out.push(`export const LENGTH_BIAS = ${hypothesis.lengthPrefix.bias};`);
  }
  const magic = layout.head.find((f) => f.role === 'magic');
  if (magic) out.push(`export const MAGIC = Buffer.from('${magic.stats.constant}', 'hex');`);
  out.push('');
  out.push('export interface Message {');
  for (const field of [...layout.head, ...(layout.payload ? [layout.payload] : []), ...layout.tail]) {
    out.push(`  ${identifier(field.name)}: ${tsType(field)};`);
  }
  out.push('}');
  out.push('');
  out.push('export function decode(buffer: Buffer): Message | null {');
  out.push(`  if (buffer.length < ${Math.max(headerLength, 1)}) return null;`);
  out.push(totalExpression(hypothesis, layout, 'buffer'));
  if (constantLength) out.push(`  const total = ${constantLength};`);
  out.push('  if (buffer.length < total) return null;');
  out.push('  return {');
  for (const field of layout.head) {
    out.push(`    ${identifier(field.name)}: ${tsRead(field, 'buffer')},`);
  }
  if (layout.payload) {
    out.push(`    ${identifier(layout.payload.name)}: buffer.subarray(${layout.payload.offset}, Math.max(${layout.payload.offset}, total - ${trailerBytes})),`);
  }
  for (const field of layout.tail) {
    out.push(`    ${identifier(field.name)}: ${tsReadTail(field, 'total')},`);
  }
  out.push('  };');
  out.push('}');
  out.push('');

  const canEncode = Boolean(lengthField || constantLength || hypothesis.kind === 'unframed');
  if (canEncode) {
    out.push('export function encode(message: Message): Buffer {');
    const variable = layout.payload ? 'message.payload.length' : '0';
    if (constantLength) {
      out.push(`  const total = ${constantLength};`);
    } else if (hypothesis.lengthPrefix) {
      out.push(`  const total = HEADER_LENGTH + ${variable} + TRAILER_LENGTH;`);
    } else {
      out.push(`  const total = HEADER_LENGTH + ${variable} + TRAILER_LENGTH;`);
    }
    out.push('  const out = Buffer.alloc(total);');
    for (const field of layout.head) {
      out.push('  ' + tsWrite(field, 'message', 'total'));
    }
    if (layout.payload) out.push(`  message.${identifier(layout.payload.name)}.copy(out, ${layout.payload.offset});`);
    if (checksum && checksumImpl) {
      out.push(`  ${tsWriteTail(checksum, `computeChecksum(out.subarray(${checksumRange(checksum)}))`, 'total')}`);
    } else if (checksum) {
      out.push(`  // ${checksum.name}: no inverse for ${checksum.evidence[0]}; supply the field yourself`);
    }
    out.push('  return out;');
    out.push('}');
    out.push('');
  } else {
    out.push('// no length field was inferred, so message boundaries cannot be reconstructed for encoding');
  }

  if (checksum && checksumImpl) {
    out.push(...checksumImpl.helpers);
    out.push('');
    out.push('export function computeChecksum(data: Buffer): number {');
    out.push(`  return ${checksumImpl.expression};`);
    out.push('}');
    out.push('');
    out.push('export function verify(buffer: Buffer): boolean {');
    out.push('  const message = decode(buffer);');
    out.push('  if (!message) return false;');
    out.push(`  const total = ${constantLength ? String(constantLength) : 'buffer.length'};`);
    out.push(
      `  return message.${identifier(checksum.name)} === computeChecksum(buffer.subarray(${checksumRange(checksum)}));`,
    );
    out.push('}');
  }

  return out.join('\n') + '\n';
}

function emitPython(analysis: FlowAnalysis, directionLabel: string, layout: Layout): string {
  const { hypothesis } = layout;
  const headerLength = headerBytes(layout);
  const trailerBytes = trailerLength(layout);
  const lengthField = layout.head.find((f) => f.role === 'length');
  const constantLength = hypothesis.kind === 'fixed' ? hypothesis.fixed!.size : null;
  const checksum = layout.checksum;
  const checksumImpl = checksum ? checksumSource(checksum.algorithm ?? '') : null;

  const out: string[] = [];
  out.push(`"""Generated by protopath ${VERSION} from ${analysis.capturePath || analysis.forward.label}`);
  out.push('');
  out.push(`Direction: ${directionLabel}`);
  out.push(`Framing: ${describe(hypothesis)} (confidence ${hypothesis.score.toFixed(2)})`);
  out.push('Field offsets are inferred; verify them before trusting them.');
  out.push('"""');
  out.push('');
  out.push('from __future__ import annotations');
  out.push('');
  out.push('from dataclasses import dataclass');
  out.push('');
  out.push(`HEADER_LENGTH = ${headerLength}`);
  out.push(`TRAILER_LENGTH = ${trailerBytes}`);
  if (lengthField && hypothesis.lengthPrefix) out.push(`LENGTH_BIAS = ${hypothesis.lengthPrefix.bias}`);
  const magic = layout.head.find((f) => f.role === 'magic');
  if (magic) out.push(`MAGIC = bytes.fromhex("${magic.stats.constant}")`);
  out.push('');
  out.push('');
  out.push('@dataclass');
  out.push('class Message:');
  for (const field of [...layout.head, ...(layout.payload ? [layout.payload] : []), ...layout.tail]) {
    out.push(`    ${identifier(field.name)}: ${pyType(field)}`);
  }
  out.push('');
  out.push('');
  out.push('def decode(buffer: bytes) -> Message | None:');
  out.push(`    if len(buffer) < ${Math.max(headerLength, 1)}:`);
  out.push('        return None');
  out.push(totalExpression(hypothesis, layout, 'buffer', 'py'));
  if (constantLength) out.push(`    total = ${constantLength}`);
  out.push('    if len(buffer) < total:');
  out.push('        return None');
  out.push('    return Message(');
  for (const field of [...layout.head, ...(layout.payload ? [layout.payload] : []), ...layout.tail]) {
    out.push(`        ${identifier(field.name)}=${pyRead(field, 'buffer', 'total', layout)},`);
  }
  out.push('    )');
  out.push('');

  const canEncode = Boolean(lengthField || constantLength || hypothesis.kind === 'unframed');
  if (canEncode) {
    out.push('');
    out.push('def encode(message: Message) -> bytes:');
    if (constantLength) {
      out.push(`    total = ${constantLength}`);
    } else if (layout.payload) {
      out.push('    total = HEADER_LENGTH + len(message.payload) + TRAILER_LENGTH');
    } else {
      out.push('    total = HEADER_LENGTH + TRAILER_LENGTH');
    }
    out.push('    out = bytearray(total)');
    for (const field of layout.head) {
      out.push('    ' + pyWrite(field, 'message', 'total'));
    }
    if (layout.payload) {
      out.push(`    out[${layout.payload.offset}:${layout.payload.offset} + len(message.payload)] = message.payload`);
    }
    if (checksum && checksumImpl) {
      const range = pythonSlice(checksum, 'out', 'total');
      out.push(`    out[total - ${checksum.offset + checksum.length}:total - ${checksum.offset}] = compute_checksum(${range}).to_bytes(${checksum.length}, "${checksum.endian === 'le' ? 'little' : 'big'}")`);
    }
    out.push('    return bytes(out)');
  }

  if (checksum && checksumImpl) {
    out.push('');
    out.push('');
    out.push(...checksumImpl.pythonHelpers);
    out.push('');
    out.push('');
    out.push('def compute_checksum(data: bytes) -> int:');
    out.push(`    return ${checksumImpl.pythonExpression}`);
    out.push('');
    out.push('');
    out.push('def verify(buffer: bytes) -> bool:');
    out.push('    message = decode(buffer)');
    out.push('    if message is None:');
    out.push('        return False');
    out.push(
      `    return message.${identifier(checksum.name)} == compute_checksum(${pythonSlice(checksum, 'buffer', 'len(buffer)')})`,
    );
  }

  return out.join('\n') + '\n';
}

function headerBytes(layout: Layout): number {
  const ends = layout.head.filter((f) => f.length > 0).map((f) => f.offset + f.length);
  return ends.length === 0 ? layout.payload?.offset ?? 0 : Math.max(0, ...ends);
}

function trailerLength(layout: Layout): number {
  return layout.tail.reduce((max, f) => Math.max(max, f.offset + f.length), 0);
}

function totalExpression(hypothesis: FramingHypothesis, layout: Layout, source: string, language: 'ts' | 'py' = 'ts'): string {
  if (hypothesis.kind === 'fixed' && hypothesis.fixed) {
    // The caller emits the constant total for fixed-size framing.
    return '';
  }
  const lengthField = layout.head.find((f) => f.role === 'length');
  if (hypothesis.lengthPrefix && lengthField) {
    const offset = lengthField.offset;
    const width = lengthField.width ?? 1;
    const endian = lengthField.endian ?? 'be';
    const raw =
      language === 'ts'
        ? width === 1
          ? `${source}[${offset}]!`
          : `${source}.readUInt${width * 8}${endian === 'le' ? 'LE' : 'BE'}(${offset})`
        : `int.from_bytes(${source}[${offset}:${offset + width}], "${endian === 'le' ? 'little' : 'big'}")`;
    const bias = hypothesis.lengthPrefix.bias;
    const expression = bias === 0 ? raw : bias > 0 ? `${raw} + ${bias}` : `${raw} - ${Math.abs(bias)}`;
    return language === 'ts' ? `  const total = ${expression};` : `    total = ${expression}`;
  }
  return language === 'ts' ? `  const total = ${source}.length;` : `    total = len(${source})`;
}

function checksumRange(checksum: Field): string {
  return `0, total - ${checksum.offset + checksum.length}`;
}

/** Python slice covering the checksummed bytes, given the buffer name and its length expression. */
function pythonSlice(checksum: Field, source: string, lengthExpression: string): string {
  return `${source}[0:${lengthExpression} - ${checksum.offset + checksum.length}]`;
}

function tsType(field: Field): string {
  if (field.role === 'text') return 'string';
  if (field.role === 'payload' || field.role === 'magic' || field.role === 'unknown') return 'Buffer';
  return 'number';
}

function pyType(field: Field): string {
  if (field.role === 'text') return 'str';
  if (field.role === 'payload' || field.role === 'magic' || field.role === 'unknown') return 'bytes';
  return 'int';
}

function tsRead(field: Field, source: string): string {
  if (field.role === 'text') {
    const end = field.length > 0 ? String(field.offset + field.length) : 'total';
    return `${source}.subarray(${field.offset}, ${end}).toString('latin1')`;
  }
  if (field.role === 'payload' || field.role === 'magic' || field.role === 'unknown') {
    return `${source}.subarray(${field.offset}, ${field.offset + field.length})`;
  }
  const width = field.length;
  const endian = field.endian === 'le' ? 'LE' : 'BE';
  if (width === 1) return `${source}[${field.offset}]!`;
  return `${source}.readUInt${width * 8}${endian}(${field.offset})`;
}

function tsReadTail(field: Field, total: string): string {
  const position = `${total} - ${field.offset + field.length}`;
  const width = field.length;
  const endian = field.endian === 'le' ? 'LE' : 'BE';
  if (width === 1) return `buffer[${position}]!`;
  return `buffer.readUInt${width * 8}${endian}(${position})`;
}

function tsWrite(field: Field, message: string, total: string): string {
  const offset = field.offset;
  const width = field.length;
  const endian = field.endian === 'le' ? 'LE' : 'BE';

  if (field.role === 'length') {
    const value = `${total} - LENGTH_BIAS`;
    if (width === 1) return `out[${offset}] = ${value};`;
    return `out.writeUInt${width * 8}${endian}(${value}, ${offset});`;
  }
  if (field.role === 'magic') return `Buffer.from('${field.stats.constant}', 'hex').copy(out, ${offset});`;
  if (field.role === 'text') return `out.write(${message}.${identifier(field.name)}, ${offset}, ${width}, 'latin1');`;
  if (field.role === 'payload' || field.role === 'unknown') return '';
  if (width === 1) return `out[${offset}] = ${message}.${identifier(field.name)};`;
  return `out.writeUInt${width * 8}${endian}(${message}.${identifier(field.name)}, ${offset});`;
}

/** Writes a tail-anchored field, whose position depends on the total message length. */
function tsWriteTail(field: Field, value: string, total: string): string {
  const width = field.length;
  const endian = field.endian === 'le' ? 'LE' : 'BE';
  const position = `${total} - ${field.offset + width}`;
  if (width === 1) return `out[${position}] = ${value};`;
  return `out.writeUInt${width * 8}${endian}(${value}, ${position});`;
}

function pyRead(field: Field, source: string, total: string, layout: Layout): string {
  if (field.role === 'payload') {
    const trailer = trailerLength(layout);
    return `${source}[${field.offset}:max(${field.offset}, ${total} - ${trailer})]`;
  }
  if (field.role === 'text') {
    const end = field.length > 0 ? String(field.offset + field.length) : 'total';
    return `${source}[${field.offset}:${end}].decode("latin1")`;
  }  if (field.role === 'magic' || field.role === 'unknown') return `${source}[${field.offset}:${field.offset + field.length}]`;
  const width = field.length;
  const endian = field.endian ?? 'be';
  const start = field.anchor === 'tail' ? `${total} - ${field.offset + width}` : `${field.offset}`;
  if (width === 1) return `${source}[${start}]`;
  return `int.from_bytes(${source}[${start}:${start} + ${width}], "${endian === 'le' ? 'little' : 'big'}")`;
}

function pyWrite(field: Field, message: string, total: string): string {
  const width = field.length;
  const endian = field.endian ?? 'be';
  if (field.role === 'length') {
    return `out[${field.offset}:${field.offset + width}] = (${total} - LENGTH_BIAS).to_bytes(${width}, "${endian === 'le' ? 'little' : 'big'}")`;
  }
  if (field.role === 'magic') return `out[${field.offset}:${field.offset + width}] = bytes.fromhex("${field.stats.constant}")`;
  if (field.role === 'text') return `out[${field.offset}:${field.offset + width}] = ${message}.${identifier(field.name)}.encode("latin1")[0:${width}]`;
  if (field.role === 'payload' || field.role === 'unknown') return 'pass';
  return `out[${field.offset}:${field.offset + width}] = ${message}.${identifier(field.name)}.to_bytes(${width}, "${endian === 'le' ? 'little' : 'big'}")`;
}

function identifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_');
}

function describe(hypothesis: FramingHypothesis): string {
  if (hypothesis.lengthPrefix) {
    const s = hypothesis.lengthPrefix;
    return `length-prefixed, ${s.size}-byte ${s.endian} length at offset ${s.lenOffset} with bias ${s.bias}`;
  }
  if (hypothesis.startMarker) return `start marker 0x${hypothesis.startMarker.marker.toString('hex')}`;
  if (hypothesis.delimiter) return `delimiter 0x${hypothesis.delimiter.terminator.toString('hex')}`;
  if (hypothesis.fixed) return `fixed ${hypothesis.fixed.size}-byte messages`;
  return 'unframed';
}
