import type { Buffer } from 'node:buffer';
import { fieldSpan, fieldValue, type Field } from '../infer/fields.js';
import type { FlowAnalysis } from '../pipeline.js';
import { VERSION } from '../pipeline.js';

/**
 * Emits a mutation harness that reuses the generated client for encoding and verification.
 *
 * The harness is deliberately dumb: it mutates one field at a time, sends the message, and
 * records which mutation stopped the peer from answering. Anything smarter would need a
 * model of the target's parser, which is exactly what we do not have.
 */
export function emitFuzzer(analysis: FlowAnalysis): string {
  const direction = analysis.primary === 'forward' ? analysis.forward : analysis.reverse;
  const fields = direction.fields.filter((f) => f.role !== 'checksum');
  const sample = direction.messages[0];

  if (!sample || fields.length === 0) {
    return `# no confident message model; nothing to fuzz\n`;
  }

  const host = analysis.flow.b.ip;
  const port = analysis.flow.b.port;
  const ctorArgs = fields.map((field) => `${identifier(field.name)}=${pyLiteral(field, sample.bytes)}`);
  const mutationTargets = fields
    .filter((f) => f.role === 'payload' || f.role === 'opcode' || f.role === 'unknown')
    .map((f) => `"${identifier(f.name)}"`);

  return `"""Generated by protopath ${VERSION} from ${pyPath(analysis.capturePath) || analysis.forward.label}

Mutation harness for ${direction.label}.
Import path setup assumes fuzz.py sits next to client.py, which is how \`protopath emit\` writes it.

Each run sends one mutated message, waits for a reply, and records the outcome. A target
that stops replying is interesting; a target that replies with a decodable message is not.
"""

from __future__ import annotations

import random
import socket
import sys

from client import Message, decode, encode

HOST = "${host}"
PORT = ${port}
TIMEOUT = 0.5
ITERATIONS = 200
SEED = 1
TARGETS = [${mutationTargets.join(', ')}]

BASE = Message(${ctorArgs.join(', ')})


def mutate(message: Message, target: str, rng: random.Random) -> Message:
    if target == "payload":
        body = bytearray(message.payload) or bytearray(4)
        index = rng.randrange(len(body))
        body[index] ^= 1 << rng.randrange(8)
        return Message(**{**message.__dict__, "payload": bytes(body)})

    original = getattr(message, target)
    if isinstance(original, int):
        return Message(**{**message.__dict__, target: rng.randrange(0, 1 << 16)})

    return message


def main() -> int:
    rng = random.Random(SEED)
    outcomes: dict[str, dict[str, int]] = {target: {"reply": 0, "silent": 0, "error": 0} for target in TARGETS}

    for iteration in range(ITERATIONS):
        target = rng.choice(TARGETS)
        message = mutate(BASE, target, rng)
        try:
            payload = encode(message)
        except Exception:
            outcomes[target]["error"] += 1
            continue

        try:
            with socket.create_connection((HOST, PORT), timeout=TIMEOUT) as sock:
                sock.sendall(payload)
                data = sock.recv(65535)
        except OSError:
            outcomes[target]["silent"] += 1
            continue

        if data and decode(data) is not None:
            outcomes[target]["reply"] += 1
        else:
            outcomes[target]["error"] += 1

    for target, counts in outcomes.items():
        print(f"{target:20s} reply={counts['reply']:4d} silent={counts['silent']:4d} undecodable={counts['error']:4d}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
`;
}

function pyLiteral(field: Field, message: Buffer): string {
  if (field.role === 'payload') return 'b""';
  if (field.role === 'magic' || field.role === 'unknown') {
    const span = fieldSpan(message, field);
    const hex = span ? message.subarray(span[0], span[1]).toString('hex') : '';
    return `bytes.fromhex("${hex}")`;
  }
  const value = fieldValue(message, field);
  if (field.role === 'text') return JSONString(String(value ?? ''));
  if (typeof value === 'number') return String(value);
  return '0';
}

function JSONString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function pyPath(path: string): string {
  return path.replace(/\\/g, '/');
}

function identifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_');
}
