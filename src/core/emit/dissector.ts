import type { FlowAnalysis } from '../pipeline.js';
import { VERSION } from '../pipeline.js';
import type { Field } from '../infer/fields.js';
import type { FramingHypothesis } from '../infer/framing.js';

export interface DissectorOptions {
  /** Protocol name used by Wireshark; must be a valid identifier. */
  name?: string;
  /** TCP or UDP port the dissector binds to. Defaults to the server port of the flow. */
  port?: number;
}

/**
 * Emits a Wireshark Lua dissector for one direction of an inferred protocol.
 *
 * The dissector consumes every message in a segment and returns the number of bytes it
 * handled, so a segment carrying several messages works without configuration. A message
 * split across segments needs Wireshark's TCP reassembly enabled; that is stated in the
 * generated header rather than silently assumed.
 */
export function emitDissector(analysis: FlowAnalysis, options: DissectorOptions = {}): string {
  const direction = analysis[directionKey(analysis)];
  const name = options.name ?? 'protopath_inferred';
  const port = options.port ?? serverPort(analysis);
  const table = analysis.flow.transport === 'tcp' ? 'tcp.port' : 'udp.port';
  const fields = direction.fields;
  const best = direction.best;
  const payloadIsText = direction.semantics.payload.encoding === 'text';

  if (!best || fields.length === 0) {
    return unframedDissector(name, table, port, analysis);
  }

  const lines: string[] = [];
  lines.push(`-- ${name}.lua - generated by protopath ${VERSION}`);
  lines.push(`-- flow: ${analysis.forward.label}`);
  lines.push(`-- direction: ${direction.label}`);
  lines.push(`-- framing: ${describeFraming(best)}`);
  lines.push(`-- framing confidence: ${best.score.toFixed(2)} over ${best.messages.length} messages`);
  lines.push('-- analysis, not ground truth: verify field widths against a known-good implementation before shipping.');
  lines.push(`-- enable Analyze > Enabled Protocols > "Allow subdissector to reassemble TCP streams" for split messages.`);
  lines.push('');
  lines.push(`local p_inferred = Proto("${name}", "Protopath inferred protocol")`);
  lines.push('');
  lines.push('local f = {}');

  for (const field of fields) {
    lines.push(`f.${luaIdent(field.name)} = ${protoFieldExpression(name, field, payloadIsText)}`);
  }

  lines.push('');
  lines.push(`p_inferred.fields = { ${fields.map((field) => `f.${luaIdent(field.name)}`).join(', ')} }`);
  lines.push('');
  lines.push(`function p_inferred.dissector(buffer, pinfo, tree)`);
  lines.push('  local length = buffer:len()');
  lines.push('  if length == 0 then return 0 end');
  lines.push('  pinfo.cols.protocol = "PROTOPATH"');
  lines.push('');
  lines.push(...dissectBody(best, fields));
  lines.push('end');
  lines.push('');
  lines.push(`local ${table.replace('.', '_')} = DissectorTable.get("${table}")`);
  lines.push(`${table.replace('.', '_')}:add(${port}, p_inferred)`);

  return lines.join('\n');
}

function dissectBody(best: FramingHypothesis, fields: Field[]): string[] {
  const out: string[] = [];
  const head = fields.filter((f) => f.anchor === 'head' && f.role !== 'payload').sort((a, b) => a.offset - b.offset);
  const payload = fields.find((f) => f.role === 'payload');
  const tail = fields.filter((f) => f.anchor === 'tail').sort((a, b) => b.offset - a.offset);

  if (best.kind === 'length-prefix' && best.lengthPrefix) {
    const spec = best.lengthPrefix;
    const bias = spec.bias;
    out.push('  local cursor = 0');
    out.push('  while cursor < length do');
    out.push('    if cursor + ' + (spec.lenOffset + spec.size) + ' > length then break end');
    const read = luaRead(`buffer(cursor + ${spec.lenOffset}, ${spec.size})`, spec.size, spec.endian);
    out.push(`    local total = ${read}${bias === 0 ? '' : bias > 0 ? ` + ${bias}` : ` - ${Math.abs(bias)}`}`);
    out.push('    if total <= 0 or cursor + total > length then break end');
    out.push(`    local msg = tree:add(p_inferred, buffer(cursor, total), "message")`);
    for (const field of head) {
      out.push(`    ${luaAdd(field, 'cursor', 'total', 'msg')}`);
    }
    if (payload) {
      const start = payload.offset;
      const trailerBytes = tail.reduce((n, f) => Math.max(n, f.offset + f.length), 0);
      out.push(`    local payload_length = total - ${start} - ${trailerBytes}`);
      out.push(`    if payload_length > 0 then msg:add(f.${luaIdent(payload.name)}, buffer(cursor + ${start}, payload_length)) end`);
    }
    for (const field of tail) {
      out.push(`    ${luaAdd(field, 'cursor', 'total', 'msg')}`);
    }
    out.push('    cursor = cursor + total');
    out.push('  end');
    out.push('  return cursor');
    return out;
  }

  if (best.kind === 'start-marker' && best.startMarker) {
    const hex = best.startMarker.marker.toString('hex');
    out.push(`  local marker = ByteArray.new("${hex}"):tvb("marker")`);
    out.push('  local cursor = 0');
    out.push('  while true do');
    out.push('    local at = buffer(cursor):find(marker, 0)');
    out.push('    if not at then break end');
    out.push('    at = cursor + at');
    out.push('    local next_at = buffer(at + 1):find(marker, 0)');
    out.push('    local stop = next_at and (at + 1 + next_at) or length');
    out.push('    local msg = tree:add(p_inferred, buffer(at, stop - at), "message")');
    for (const field of head) {
      out.push(`    ${luaAddAbsolute(field, 'at', 'msg')}`);
    }
    if (payload) {
      out.push(`    if stop - at > ${payload.offset} then msg:add(f.${luaIdent(payload.name)}, buffer(at + ${payload.offset}, stop - at - ${payload.offset})) end`);
    }
    out.push('    cursor = stop');
    out.push('  end');
    out.push('  return length');
    return out;
  }

  if (best.kind === 'delimiter' && best.delimiter) {
    out.push(`  local text = buffer():string()`);
    out.push(`  local msg = tree:add(p_inferred, buffer(), "text message")`);
    out.push(`  if text:sub(-${best.delimiter.terminator.length}) == "${escapeLua(best.delimiter.terminator.toString('latin1'))}" then`);
    out.push(`    msg:add(f.${luaIdent(fields[0]!.name)}, buffer(0, length - ${best.delimiter.terminator.length}))`);
    out.push('  else');
    out.push(`    msg:add(f.${luaIdent(fields[0]!.name)}, buffer(0, length))`);
    out.push('  end');
    out.push('  return length');
    return out;
  }

  if (best.kind === 'fixed' && best.fixed) {
    out.push(`  local size = ${best.fixed.size}`);
    out.push('  local cursor = 0');
    out.push('  while cursor + size <= length do');
    out.push('    local msg = tree:add(p_inferred, buffer(cursor, size), "message")');
    for (const field of head) {
      out.push(`    ${luaAdd(field, 'cursor', 'size', 'msg')}`);
    }
    out.push('    cursor = cursor + size');
    out.push('  end');
    out.push('  return cursor');
    return out;
  }

  out.push('  tree:add(p_inferred, buffer(), "unframed payload")');
  out.push('  return length');
  return out;
}

function luaAdd(field: Field, base: string, totalVar: string, tree: string): string {
  if (field.anchor === 'tail') {
    return `${tree}:add(f.${luaIdent(field.name)}, buffer(${base} + ${totalVar} - ${field.offset + field.length}, ${field.length}))`;
  }
  return `${tree}:add(f.${luaIdent(field.name)}, buffer(${base} + ${field.offset}, ${field.length}))`;
}

function luaAddAbsolute(field: Field, base: string, tree: string): string {
  return `${tree}:add(f.${luaIdent(field.name)}, buffer(${base} + ${field.offset}, ${field.length}))`;
}

function luaRead(accessor: string, size: number, endian: 'le' | 'be'): string {
  const prefix = endian === 'le' ? 'le_' : '';
  if (size === 1) return `${accessor}:${prefix}uint()`;
  return `${accessor}:${prefix}${size === 2 ? 'uint16' : 'uint32'}()`;
}

function protoFieldExpression(protoName: string, field: Field, payloadIsText: boolean): string {
  const label = field.name.replace(/_/g, ' ');
  const id = `${protoName}.${luaIdent(field.name)}`;
  if (field.role === 'text') return `ProtoField.string("${id}", "${label}")`;
  if (field.role === 'payload') {
    return payloadIsText
      ? `ProtoField.string("${id}", "${label}")`
      : `ProtoField.bytes("${id}", "${label}")`;
  }
  if (field.role === 'magic') return `ProtoField.bytes("${id}", "${label}")`;
  const width = field.length > 0 ? field.length : field.width ?? 1;
  if (width === 1) return `ProtoField.uint8("${id}", "${label}", base.${field.role === 'opcode' ? 'HEX' : 'DEC'})`;
  if (width === 2) return `ProtoField.uint16("${id}", "${label}", base.${field.role === 'checksum' ? 'HEX' : 'DEC'})`;
  return `ProtoField.uint32("${id}", "${label}", base.${field.role === 'checksum' ? 'HEX' : 'DEC'})`;
}

function unframedDissector(name: string, table: string, port: number, analysis: FlowAnalysis): string {
  return [
    `-- ${name}.lua - generated by protopath ${VERSION}`,
    `-- no confident framing was recovered for ${analysis.forward.label}`,
    `-- this dissector shows the raw payload so a recording can still be inspected`,
    '',
    `local p_inferred = Proto("${name}", "Protopath inferred protocol (unframed)")`,
    '',
    'function p_inferred.dissector(buffer, pinfo, tree)',
    '  if buffer:len() == 0 then return 0 end',
    '  pinfo.cols.protocol = "PROTOPATH"',
    '  tree:add(p_inferred, buffer(), "raw payload")',
    '  return buffer:len()',
    'end',
    '',
    `DissectorTable.get("${table}"):add(${port}, p_inferred)`,
  ].join('\n');
}

function luaIdent(value: string): string {
  return value.replace(/[^a-zA-Z0-9_]/g, '_');
}

/** Escapes a byte string for a double-quoted Lua literal. */
function escapeLua(value: string): string {
  let out = '';
  for (const char of value) {
    const code = char.charCodeAt(0);
    if (char === '\\' || char === '"') out += `\\${char}`;
    else if (code >= 0x20 && code <= 0x7e) out += char;
    else out += `\\${code.toString().padStart(3, '0')}`;
  }
  return out;
}

function serverPort(analysis: FlowAnalysis): number {
  return analysis.primary === 'forward' ? analysis.flow.b.port : analysis.flow.a.port;
}

function directionKey(analysis: FlowAnalysis): 'forward' | 'reverse' {
  return analysis.primary;
}

function describeFraming(hypothesis: FramingHypothesis): string {
  if (hypothesis.lengthPrefix) {
    const s = hypothesis.lengthPrefix;
    return `length-prefix, ${s.size}-byte ${s.endian} length at offset ${s.lenOffset}, bias ${s.bias}`;
  }
  if (hypothesis.startMarker) return `start-marker 0x${hypothesis.startMarker.marker.toString('hex')}`;
  if (hypothesis.delimiter) return `delimiter 0x${hypothesis.delimiter.terminator.toString('hex')}`;
  if (hypothesis.fixed) return `fixed ${hypothesis.fixed.size} bytes`;
  return 'unframed';
}

